"""
signal_gen —— 信号生成与分析工具包。

模块划分：
    core       信号生成器（全部支持随机种子，可完全复现）
    standards  标准测试信号的频谱规格（EIA RS-426-B / IEC 60268-1）
    spectrum   频谱分析与 1/6 倍频程平滑
    audio_io   量化与 WAV 读写
    report    外部音频文件的分析与双栏报告图
    cli        命令行入口
    gui        图形界面入口（tkinter）

设计约定：
    1. 所有生成器为纯函数：相同参数 + 相同 seed -> 逐比特相同的输出。
    2. 频谱一律归一到 dBFS（满幅正弦 = 0 dBFS），跨脚本可比。
    3. 1/6 倍频程按 IEC 61260 / ANSI S1.11 采用**频带功率积分**，
       粉噪在各频带上读数相同（曲线平直）。
"""

